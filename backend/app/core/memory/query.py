"""检索 query 构造。

L2 事实层的召回质量有个天花板：库里存得再准，query 向量对不上也召不回来。
多轮对话里用户的话天然残缺——「那个周三换一天行吗」这句里，"周三"要跟
「每周三晚上固定加班」对上，但整句被"换一天行吗"稀释，距离 0.576 刚好越过
0.55 的阈值线，召不回。表现出来就是记忆系统在续问时时灵时不灵，没有报错。

## 为什么是"独立第二路"而不是"拼接改写"

最先想到的是把上文拼在当前句前面当成一条新 query。实测（backend 真实
embedding 网关，4 组续问样本）证明这个方案是错的：

| 当前句 | 原句单路 | 拼接单路 | 原句 + 上文双路 |
|---|---|---|---|
| 那午饭呢？ | **0.479 ✓** | 0.641 ✗ | **0.479 ✓** |
| 那有什么不能放的吗 | 0.718 ✗ | 0.685 ✗ | 0.718 ✗ |
| 这样安排我肩膀受得了吗 | **0.469 ✓** | 0.536 ✓ | **0.469 ✓** |
| 那个周三换一天行吗 | 0.576 ✗ | **0.455 ✓** | **0.470 ✓** |
| **命中** | **2/4** | **2/4** | **3/4** |

关键是第一行：「那午饭呢？」原句距离 0.479 本来召得回，拼上上文变成 0.641
反而召不回了。原因是短句里关键词的权重占比极高（"午饭"几乎就是整句），
掺进上一轮几十个字的长文本会把它稀释掉。拼接是在用"补充信息"换"信号强度"，
而这笔交易并不总是划算——它换回一个（第四行），又赔掉一个（第一行），净收益零。

双路则没有这个取舍：原句那一路始终在，取两路的最小距离，所以**严格不劣于**
原来的单路召回，只可能多召回、不可能少召回。这个性质比多命中一条更重要——
优化召回不该以在别处引入回归为代价。

第二行两种方案都召不回，说明拼接与双路都救不了跨度太大的语义跳跃（"不能放的"
→"不吃香菜"）。那属于 query 改写要解决的问题，得靠 LLM，而这条召回在用户等
回复的主链路上，不适合再插一次同步模型调用。留给后续。

## 为什么只在句子确实依赖上文时才开第二路

无条件加第二路会引入误召回：当前句语义本来充分时（「我右肩疼，今天能练推举吗」），
上一轮的内容多半是另一个话题，凭空多一路检索只会把无关事实拉进 0.55 以内。
所以先判断残缺，再决定是否补。
"""

# 出现在句中任意位置即判定为依赖上文。
# 只收两字以上、作为子串足够特异的词——单字词按子串匹配误命中太多
# （"还"会命中"还有""归还"），那些放到 _LEADING_MARKERS 里按句首判断。
_INLINE_MARKERS = (
    # 指示代词：指向上文提过的某个对象
    "这个", "这份", "这些", "这条", "这套", "这样", "这种", "这次",
    "那个", "那份", "那些", "那条", "那套", "那样", "那种", "那次",
    # 回指
    "上面", "上述", "上一个", "上次", "刚才", "刚刚", "前面", "之前", "方才",
    # 承接式修改：动作的宾语在上文里
    "改成", "换成", "调成", "改一下", "换一下", "调一下", "照这个", "按这个",
    "同样", "一样",
)

# 仅当出现在句首时判定。这些词句中出现多半是普通搭配，句首出现则几乎总是
# 承接上一轮（「那午饭呢」「再给我一个」「继续说」）。
_LEADING_MARKERS = (
    "那", "再", "还", "然后", "接着", "继续", "顺便", "另外", "以及",
    "改成", "换成", "调成",
)

# 句首判断前要剥掉的前导符号，否则「，那午饭呢」这类会漏判。
_LEADING_NOISE = " \t\n，。、；：！？,.;:!?“”\"'（）()「」【】"

# 上文 query 的字符上限。助理的回复可能上千字（计划、配餐的完整说明），
# 整段送去检索会让向量糊成"健身话题"的平均值，跟每条具体事实都不近。
# 系统提示要求助理"用一两句话说明结果，细节交给卡片"，所以取开头即可。
PER_MESSAGE_CHARS = 120

# 往回取几条消息。指代基本只指向最近一轮（user + assistant = 2 条）；
# 取更多只会让上文 query 更糊。
RECENT_MESSAGES = 2


def is_referential(user_text: str) -> bool:
    """判断这句话是否残缺到需要上文才能理解。"""
    text = user_text.strip()
    if not text:
        return False

    if any(marker in text for marker in _INLINE_MARKERS):
        return True

    head = text.lstrip(_LEADING_NOISE)
    return head.startswith(_LEADING_MARKERS)


def build_context_query(user_text: str, history: list[dict]) -> str | None:
    """当前句依赖上文时，返回一条**独立**的上文 query；否则返回 None。

    返回值不含当前句——它由调用方作为第一路单独送检。两路分开送、取最小距离，
    而不是拼成一条：拼接会稀释短句里的关键词，实测反而丢召回（见模块文档）。

    返回 None 表示"不需要第二路检索"，调用方退化成原来的单通道召回。
    """
    if not history or not is_referential(user_text):
        return None

    recent = [
        str(message.get("content", "")).strip()[:PER_MESSAGE_CHARS]
        for message in history[-RECENT_MESSAGES:]
    ]
    parts = [text for text in recent if text]
    if not parts:
        return None

    return " ".join(parts)
